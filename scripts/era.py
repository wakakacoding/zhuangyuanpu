#!/usr/bin/env python3
"""纪年工具：公元 / 干支 / 年号互转（构建期库，随数据增长扩充）

用法：
    from era import ganzhi_of, ganzhi_matches, year_in_reign
    ganzhi_of(1904)          # -> '甲辰'
    ganzhi_matches(1904, '甲辰')  # -> True
    year_in_reign(1904, '光绪')   # -> True（未收录的年号返回 None）
"""

STEMS = "甲乙丙丁戊己庚辛壬癸"
BRANCHES = "子丑寅卯辰巳午未申酉戌亥"


def ganzhi_of(year: int) -> str:
    """公元年 -> 干支。以公元 4 年为甲子年起算。"""
    year = int(year)
    return STEMS[(year - 4) % 10] + BRANCHES[(year - 4) % 12]


def ganzhi_matches(year: int, gz: str) -> bool:
    return ganzhi_of(year) == gz


# 年号表：reign -> (起始公元年, 终止公元年)。录入新朝代时在此扩充。
