BRACKET_RE = re.compile(r"[（(].*?[）)]")


def norm_keys(nh: str, dynasty: str):
    """候选键序列：地名|朝代 → 地名原样 → 去括号 → 双籍首段"""
    yield f"{nh}|{dynasty}"
    yield nh
    stripped = BRACKET_RE.sub("", nh).strip()
    if stripped != nh:
        yield stripped
    if " / " in nh:
        first = nh.split(" / ")[0].strip()
        yield first
        first_s = BRACKET_RE.sub("", first).strip()
        if first_s != first:
            yield first_s


def main():
    dry = "--dry-run" in sys.argv
    geo_file = DATA / "geo_map.yaml"
    geo = yaml.safe_load(geo_file.read_text(encoding="utf-8")) or []
    geo_by_hist = {g["hist"]: g for g in geo if isinstance(g, dict) and g.get("hist")}

    pdir = DATA / "persons"
    files = sorted(f for f in pdir.glob("*.yaml") if not f.name.startswith("_"))

    filled, missed, already = [], [], 0
    geo_add = {}

    for f in files:
        doc = yaml.safe_load(f.read_text(encoding="utf-8"))
        if not isinstance(doc, dict):
            continue
        if doc.get("lat") is not None:
            already += 1
            continue
        nh = doc.get("native_hist")
        if not nh:
            missed.append((doc["id"], "(无籍贯)"))
            continue

        hit = None  # (modern, lat, lng, note, via_geo_map)
        for key in norm_keys(str(nh).strip(), doc.get("dynasty", "")):
            if key in geo_by_hist:
                g = geo_by_hist[key]
                hit = (g.get("modern"), g.get("lat"), g.get("lng"), g.get("note"), True)
                break
            if key in M:
                hit = (*M[key], False)
                break
        if not hit:
            missed.append((doc["id"], nh))
            continue

        modern, lat, lng, note, via_geo = hit
        if lat is None:
            missed.append((doc["id"], nh))
            continue
        filled.append((doc["id"], nh, modern))

        # geo_map 增补（仅当该 hist 尚不存在）
        if str(nh).strip() not in geo_by_hist:
            geo_add[str(nh).strip()] = {
                "hist": str(nh).strip(), "modern": modern,
                "lat": lat, "lng": lng, "chgis_id": None,
                "note": note or "县治坐标（约）",
            }

        if dry:
            continue

        # 回填卡片：文本级替换保留注释（native_modern 行 + 插入 lat/lng）
        text = f.read_text(encoding="utf-8")
        text = re.sub(r"^native_modern:.*$", f"native_modern: {modern}", text, count=1, flags=re.M)
        if re.search(r"^lat:", text, flags=re.M):
            text = re.sub(r"^lat:.*$", f"lat: {lat}", text, count=1, flags=re.M)
            text = re.sub(r"^lng:.*$", f"lng: {lng}", text, count=1, flags=re.M)
        else:
            text = text.replace(
                f"native_modern: {modern}\n",
                f"native_modern: {modern}\nlat: {lat}\nlng: {lng}\n",
                1,
            )
        f.write_text(text, encoding="utf-8")

    # 追加 geo_map
    if geo_add and not dry:
        lines = []
        for g in sorted(geo_add.values(), key=lambda x: x["hist"]):
            note = str(g["note"]).replace('"', "'")
            lines.append(
                f'- hist: {g["hist"]}\n  modern: {g["modern"]}\n'
                f'  lat: {g["lat"]}\n  lng: {g["lng"]}\n  chgis_id: null\n  note: "{note}"'
            )
        with geo_file.open("a", encoding="utf-8") as fh:
            fh.write("\n" + "\n".join(lines) + "\n")

    n = len(files)
    done = already + len(filled)
    print(f"{'[DRY-RUN] ' if dry else ''}总 {n} | 原有坐标 {already} | 新回填 {len(filled)} | 未命中 {len(missed)}")
    print(f"坐标覆盖: {done}/{n} = {done/n*100:.1f}%（地图闸门 60% = {int(n*0.6)} 人）")
    print(f"geo_map 新增 {len(geo_add)} 条")
    if missed:
        print("--- 未命中清单（需人工补） ---")
        for pid, nh in missed:
            print(f"  {pid}: {nh}")


if __name__ == "__main__":
    main()
