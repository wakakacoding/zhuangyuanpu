def main():
    written = 0
    for (pid, name, dynasty, reign, year, hist, modern, lat, lng,
         birth, death, bio, tags) in CARDS:
        if reign not in REIGNS:
            raise SystemExit(f"{pid}: 年号 {reign} 未收录进 era.py")
        n = year - REIGNS[reign][0] + 1
        card = {
            "id": pid, "name": name, "zi": None, "hao": None,
            "birth_year": birth, "death_year": death,
            "native_hist": hist, "native_modern": modern, "lat": lat, "lng": lng,
            "dynasty": dynasty, "reign": reign,
            "exam_year": year, "ganzhi": ganzhi_of(year),
            "ke_ci": f"{reign}{cn_num(n)}年{ganzhi_of(year)}科",
            "rank_detail": "一甲第一名（状元）",
            "bio_short": bio, "tags": tags, "status": "published",
        }
        (PERSONS / f"{pid}.yaml").write_text(
            yaml.safe_dump(card, allow_unicode=True, sort_keys=False, width=120),
            encoding="utf-8")
        written += 1

    # geo_map 合并（按 hist 去重）
    geo = yaml.safe_load(GEO.read_text(encoding="utf-8")) or []
    existing = {g.get("hist") for g in geo}
    added = 0
    for (_, _, _, _, _, hist, modern, lat, lng, *_) in CARDS:
        if hist not in existing:
            geo.append({"hist": hist, "modern": modern, "lat": lat, "lng": lng,
                        "chgis_id": None, "note": "县治坐标（约）"})
            existing.add(hist)
            added += 1
    GEO.write_text(yaml.safe_dump(geo, allow_unicode=True, sort_keys=False, width=120),
                   encoding="utf-8")
    print(f"速览卡写入 {written} 张；geo_map 新增 {added} 条（累计 {len(geo)} 条）")


if __name__ == "__main__":
    main()
