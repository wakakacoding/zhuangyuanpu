def cn_num(n: int) -> str:
    """年号序数转中文：1->元, 2->二, ..., 21->二十一"""
    if n == 1:
        return "元"
    d = "零一二三四五六七八九"
    if n < 10:
        return d[n]
    if n < 20:
        return "十" + (d[n % 10] if n % 10 else "")
    return d[n // 10] + "十" + (d[n % 10] if n % 10 else "")


